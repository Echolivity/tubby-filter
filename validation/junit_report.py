"""Turn pytest JUnit XML into validation/V22_TEST_RESULTS.md (every test, with status).

    python3 validation/junit_report.py <label>=<junit.xml> [...] > validation/V22_TEST_RESULTS.md

Status mapping (brief section 14):
  passed -> PASS; failure/error -> FAIL; xfail (strict known issue) -> FAIL (known issue, expected);
  skipped -> NOT TESTED. Native gen~ / Live items are appended as BLOCKED.
Procedure/expected text is taken from each test's docstring (or its name when it has none).
"""
import ast, os, platform, sys, xml.etree.ElementTree as ET

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def docstrings():
    out = {}
    for rel in ("tests/test_v22.py", "tests/test_regression.py", "experiments/test_candidate.py"):
        tree = ast.parse(open(os.path.join(ROOT, rel)).read())
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test"):
                out[(rel, node.name)] = (ast.get_docstring(node) or "").split("\n\n")[0].replace("\n", " ")
    return out


def main(args):
    docs = docstrings()
    env = (f"[sim] GSX execution of the shipped .genexpr (numba) — {platform.platform()}, Python "
           f"{platform.python_version()}; not native gen~, not Ableton Live")
    rows, counts = [], {}
    for arg in args:
        label, path = arg.split("=", 1)
        for tc in ET.parse(path).getroot().iter("testcase"):
            cls, name = tc.get("classname"), tc.get("name")
            rel = cls.replace(".", "/") + ".py"
            base = name.split("[")[0]
            fail, err = tc.find("failure"), tc.find("error")
            skip = tc.find("skipped")
            if skip is not None and "xfail" in (skip.get("type", "") + skip.get("message", "")).lower():
                status, actual = "FAIL", "known issue (strict xfail): " + skip.get("message", "")[:160]
            elif skip is not None:
                status, actual = "NOT TESTED", "skipped: " + skip.get("message", "")[:120]
            elif fail is not None or err is not None:
                e = fail if fail is not None else err
                status, actual = "FAIL", (e.get("message") or "")[:160]
            else:
                status, actual = "PASS", f"passed in {float(tc.get('time', 0)):.2f} s"
            counts[(label, status)] = counts.get((label, status), 0) + 1
            proc = docs.get((rel, base), "") or base.replace("_", " ")
            rows.append((label, f"`{base}`" + (name[len(base):].replace("|", "/") if len(name) > len(base) else ""),
                         proc.replace("|", "/"), actual.replace("|", "/").replace("\n", " "), status, f"`{rel}`; {os.path.basename(path)}"))
    print("# 2.2.0-rc1 test results\n")
    print("Generated by `validation/junit_report.py` from the pytest JUnit XML of an actual run. "
          "Nothing in this file is hand-written.\n")
    print(f"**Environment (automated tests):** {env}\n")
    print("**Status values:** PASS / FAIL = executed. BLOCKED = needs unavailable software. NOT TESTED = not attempted. "
          "A strict expected failure (a known issue whose criterion was deliberately not relaxed) is reported as **FAIL**.\n")
    print("## Summary\n")
    print("| Suite | PASS | FAIL | NOT TESTED |\n|---|---|---|---|")
    for label in dict.fromkeys(a.split("=")[0] for a in args):
        print(f"| {label} | {counts.get((label, 'PASS'), 0)} | {counts.get((label, 'FAIL'), 0)} | "
              f"{counts.get((label, 'NOT TESTED'), 0)} |")
    print("| Native gen~ compilation, Max loading, all Ableton Live items | 0 | 0 | — (**BLOCKED**: Max and Live not installed) |\n")
    print("## Every executed test\n")
    print("Expected result = the test's acceptance criterion (its docstring, or the assertion in the source).\n")
    print("| Suite | Test ID | Procedure / expected | Actual | Status | Evidence |\n|---|---|---|---|---|---|")
    for r in rows:
        print("| " + " | ".join(r) + " |")
    print("\n## BLOCKED (not executable here)\n")
    print("| ID | Requires | Procedure |\n|---|---|---|")
    for i, what in (("L1/L2", "Max + Live 12: native gen~ compilation of V2.2 and V2.1"),
                    ("Part A C01–C14", "Live 12: capture renders compared by compare_capture.py"),
                    ("G-1…LD-1", "Live 12: GUI, cutoff/reso, Motion, MIDI, automation, presets, save/reopen, "
                                 "rate change, transport, bypass, parallel, PDC, export, CPU, 60-min run"),
                    ("Listening", "an audio device and a listener (Part C)")):
        print(f"| {i} | {what} | validation/ABLETON_LIVE_12_QA.md |")


if __name__ == "__main__":
    main(sys.argv[1:])
